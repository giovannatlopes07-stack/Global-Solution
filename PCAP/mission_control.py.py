def classificar_ciclo(pontos_totais):
    """Classifica a situação do ciclo com base na pontuação acumulada."""
    if 0 <= pontos_totais <= 2:
        return f"{VERDE}{BOLD}MISSÃO ESTÁVEL{RESET}", "MISSÃO ESTÁVEL"
    elif 3 <= pontos_totais <= 5:
        return f"{AMARELO}{BOLD}MISSÃO EM ATENÇÃO{RESET}", "MISSÃO EM ATENÇÃO"
    else:
        return f"{VERMELHO}{BOLD}MISSÃO CRÍTICA{RESET}", "MISSÃO CRÍTICA"


def gerar_recomendacao(classificacoes):
    """Gera diretrizes automáticas baseadas nos status críticos encontrados."""
    recomendas = []
    if classificacoes[0] == "CRÍTICO":
        recomendas.append("Verificar controle térmico da missão.")
    if classificacoes[1] == "CRÍTICO":
        recomendas.append("Tentar restabelecer contato com a base.")
    if classificacoes[2] == "CRÍTICO":
        recomendas.append("Ativar modo de economia de energia.")
    if classificacoes[3] == "CRÍTICO":
        recomendas.append("Acionar protocolo de suporte à vida.")
    if classificacoes[4] == "CRÍTICO":
        recomendas.append("Reduzir operações não essenciais.")

    if recomendas:
        # Se houver mais de 2 itens críticos, sugere o protocolo de segurança master
        if len(recomendas) >= 3:
            return "Ativar modo de segurança e priorizar suporte à vida, energia e comunicação."
        return " ".join(recomendas)

    # Se não houver nada crítico, mas houver sistemas em atenção
    if "ATENÇÃO" in classificacoes:
        return "Monitorar sistemas em atenção e preparar plano de contingência."

    return "Manter operação normal e continuar monitoramento."


def analisar_tendencia(primeiro_risco, ultimo_risco):
    """Compara o risco do início e do fim da missão para determinar a tendência."""
    if ultimo_risco > primeiro_risco:
        return f"{VERMELHO}A missão apresentou tendência de piora.{RESET}"
    elif ultimo_risco < primeiro_risco:
        return f"{VERDE}A missão apresentou tendência de melhora.{RESET}"
    else:
        return f"{AMARELO}A missão permaneceu estável em relação ao início.{RESET}"


def colorir_status(status):
    """Apenas uma função auxiliar estética (Plus) para colorir as tags dos parâmetros."""
    if status == "NORMAL": return f"{VERDE}NORMAL{RESET}"
    if status == "ATENÇÃO": return f"{AMARELO}ATENÇÃO{RESET}"
    return f"{VERMELHO}CRÍTICO{RESET}"


