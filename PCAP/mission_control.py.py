def executar_mission_control():
    print(f"\n{CIANO}============================================================{RESET}")
    print(f"{BOLD}                     MISSION CONTROL AI                      {RESET}")
    print(f"{CIANO}============================================================{RESET}")
    print(f"{BOLD}Missão:{RESET} {NOME_MISSAO}")
    print(f"{BOLD}Equipe:{RESET} {NOME_EQUIPE}")
    print(f"{BOLD}Quantidade de ciclos analisados:{RESET} {len(DADOS_MISSAO)}")
    print(f"{CIANO}============================================================{RESET}\n")

    # Inicialização de variáveis para o relatório final
    somas_areas = [0, 0, 0, 0, 0]
    pontuacoes_ciclos = []
    total_ciclos_criticos = 0

    # Listas auxiliares para armazenar dados de cálculo das médias
    temp_lista, com_lista, bat_lista, ox_lista, est_lista = [], [], [], [], []

    # Loop principal (Estrutura de repetição exigida)
    for i, ciclo in enumerate(DADOS_MISSAO):
        num_ciclo = i + 1
        print(f"{BOLD}--- CICLO {num_ciclo} ---{RESET}")

        # Coleta dos dados brutos
        t, c, b, o, e = ciclo

        # Alimentando listas de médias
        temp_lista.append(t)
        com_lista.append(c)
        bat_lista.append(b)
        ox_lista.append(o)
        est_lista.append(e)

        # Executando as análises funcionais
        st_t, pt_t, desc_t = analisar_temperatura(t)
        st_c, pt_c, desc_c = analisar_comunicacao(c)
        st_b, pt_b, desc_b = analisar_bateria(b)
        st_o, pt_o, desc_o = analisar_oxigenio(o)
        st_e, pt_e, desc_e = analisar_estabilidade(e)

        # Acumulando riscos por área
        somas_areas[0] += pt_t
        somas_areas[1] += pt_c
        somas_areas[2] += pt_b
        somas_areas[3] += pt_o
        somas_areas[4] += pt_e

        # Exibição individual limpa no terminal
        print(f"Temperatura: {t}°C | {colorir_status(st_t)} | {desc_t}")
        print(f"Comunicação: {c}%  | {colorir_status(st_c)} | {desc_c}")
        print(f"Bateria:     {b}%  | {colorir_status(st_b)} | {desc_b}")
        print(f"Oxigênio:    {o}%  | {colorir_status(st_o)} | {desc_o}")
        print(f"Estabilidade:{e}%  | {colorir_status(st_e)} | {desc_e}")

        # Cálculos de pontuação e classificação do ciclo
        pontos_ciclo = pt_t + pt_c + pt_b + pt_o + pt_e
        pontuacoes_ciclos.append(pontos_cycle := pontos_ciclo)

        cor_classe, texto_classe = classificar_ciclo(pontos_ciclo)
        if texto_classe == "MISSÃO CRÍTICA":
            total_ciclos_criticos += 1

        recomendacao = gerar_recomendacao([st_t, st_c, st_b, st_o, st_e])

        print(f"Pontuação de risco do ciclo: {BOLD}{pontos_ciclo}{RESET}")
        print(f"Classificação do ciclo: {cor_classe}")
        print(f"Recomendação: {CIANO}{recomendacao}{RESET}")
        print("-" * 40)

    # Identificação do ciclo mais crítico e maior pontuação
    max_risco = max(pontuacoes_ciclos)
    indice_critico = pontuacoes_ciclos.index(max_risco) + 1
    risco_medio_total = sum(pontuacoes_ciclos) / len(DADOS_MISSAO)

    # Identificação da área mais afetada
    maior_risco_area = max(somas_areas)
    idx_area_afetada = somas_areas.index(maior_risco_area)
    area_mais_afetada = AREAS_MONITORADAS[idx_area_afetada]

    # Classificação final da missão baseada no risco médio
    _, classe_final = classificar_ciclo(int(risco_medio_total))

    # ==========================================
    # OUTPUT: RELATÓRIO FINAL DA MISSÃO
    # ==========================================
    print(f"\n{VERDE}============================================================{RESET}")
    print(f"{BOLD}                 RELATÓRIO FINAL DA MISSÃO                  {RESET}")
    print(f"{VERDE}============================================================{RESET}")
    print(f"{BOLD}Missão:{RESET} {NOME_MISSAO}  |  {BOLD}Equipe:{RESET} {NOME_EQUIPE}")
    print(f"{BOLD}Quantidade de ciclos analisados:{RESET} {len(DADOS_MISSAO)}\n")

    print(f"{BOLD}MÉDIAS DOS PARÂMETROS:{RESET}")
    print(f"Média de temperatura:  {sum(temp_lista)/len(temp_lista):.2f} °C")
    print(f"Média de comunicação:  {sum(com_lista)/len(com_lista):.2f}%")
    print(f"Média de bateria:      {sum(bat_lista)/len(bat_lista):.2f}%")
    print(f"Média de oxigênio:     {sum(ox_lista)/len(ox_lista):.2f}%")
    print(f"Média de estabilidade: {sum(est_lista)/len(est_lista):.2f}%\n")

    print(f"{BOLD}ANÁLISE DE INCIDENTES:{RESET}")
    print(f"Ciclo mais crítico:      Ciclo {indice_critico}")
    print(f"Maior pontuação de risco: {max_risco}")
    print(f"Risco médio da missão:    {risco_medio_total:.2f}")
    print(f"Quantidade de ciclos críticos: {total_ciclos_criticos}\n")

    print(f"{BOLD}TENDÊNCIA DA MISSÃO:{RESET}")
    print(analisar_tendencia(pontuacoes_ciclos[0], pontuacoes_ciclos[-1]))
    print()

    print(f"{BOLD}PONTUAÇÃO ACUMULADA POR ÁREA:{RESET}")
    for area, pontos in zip(AREAS_MONITORADAS, somas_areas):
        print(f"- {area}: {pontos} pontos")

    print(f"\n{BOLD}ÁREA MAIS AFETADA:{RESET}")
    print(f"{VERMELHO}{BOLD}{area_mais_afetada}{RESET}\n")

    print(f"{BOLD}CLASSIFICAÇÃO FINAL DA MISSÃO:{RESET}")
    cor_final, _ = classificar_ciclo(int(risco_medio_total))
    print(cor_final)
    print()

    print(f"{BOLD}CONCLUSÃO:{RESET}")
    if classe_final == "MISSÃO CRÍTICA":
        print(f"{VERMELHO}A missão enfrentou falhas severas intransponíveis. Protocolo de contingência total deve permanecer ativo.{RESET}")
    elif classe_final == "MISSÃO EM ATENÇÃO":
        print(f"{AMARELO}A operação registrou oscilações significativas ao longo dos ciclos analisados.\nMesmo com sinais de recuperação na última leitura, subsistemas ainda demandam cuidados e a equipe de engenharia deve preservar os protocolos de contingência ligados.{RESET}")
    else:
        print(f"{VERDE}Operação concluída com absoluto sucesso. Todos os sistemas principais se mantiveram dentro dos limites seguros na média histórica.{RESET}")
    print(f"{VERDE}============================================================{RESET}\n")


# Ponto de entrada que executa a aplicação
if __name__ == "__main__":
    executar_mission_control()